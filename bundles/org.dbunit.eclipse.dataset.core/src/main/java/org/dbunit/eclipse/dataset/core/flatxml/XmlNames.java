    /**
     * Returns whether a code point may start an XML 1.0 name.
     *
     * @param codePoint The Unicode code point to test.
     * @return True when the XML parser of the Java runtime accepts the code point at the start of a name.
     */
    public static boolean isNameStartChar(final int codePoint)
    {
        return isInRanges(NAME_START_RANGES, codePoint);
    }

    /**
     * Returns whether a code point may continue an XML 1.0 name after its first character.
     *
     * @param codePoint The Unicode code point to test.
     * @return True when the XML parser of the Java runtime accepts the code point inside a name.
     */
    public static boolean isNameChar(final int codePoint)
    {
        return isInRanges(NAME_RANGES, codePoint);
    }

    /**
     * Returns whether a character is XML white space, the {@code S} production of XML 1.0: a space, a tab, a
     * carriage return, or a line feed. It is narrower than {@link Character#isWhitespace(char)}, which also
     * accepts, for example, the form feed and the ideographic space U+3000, and what separates two things
     * for the XML parser of the Java runtime, which dbUnit loads a dataset with, is only these four.
     *
     * @param character The character to test.
     * @return True when the character is a space, a tab, a carriage return, or a line feed.
     */
    public static boolean isWhitespace(final char character)
    {
        return character == ' ' || character == '\t' || character == '\n' || character == '\r';
    }

    /**
     * Returns whether a string is a valid XML 1.0 name.
     *
     * @param name The string to test.
     * @return True when the string is non-empty, its first code point is a {@code NameStartChar}, and
     *         every later code point is a {@code NameChar}.
     */
    public static boolean isValidName(final String name)
    {
        if (name.isEmpty())
        {
            return false;
        }
        final int firstCodePoint = name.codePointAt(0);
        if (!isNameStartChar(firstCodePoint))
        {
            return false;
        }
        int index = Character.charCount(firstCodePoint);
        while (index < name.length())
        {
            final int codePoint = name.codePointAt(index);
            if (!isNameChar(codePoint))
            {
                return false;
            }
            index += Character.charCount(codePoint);
        }
        return true;
    }

    /**
     * Searches a table of ranges for a code point.
     *
     * @param ranges The first and the last code point of each range, one range after the other, in
     *               ascending order.
     * @param codePoint The code point to look for.
     * @return True when one of the ranges holds the code point.
     */
    private static boolean isInRanges(final int[] ranges, final int codePoint)
    {
        int low = 0;
        int high = ranges.length / 2 - 1;
        while (low <= high)
        {
            final int middle = (low + high) >>> 1;
            if (codePoint < ranges[2 * middle])
            {
                high = middle - 1;
            }
            else if (codePoint > ranges[2 * middle + 1])
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }
        return false;
    }
